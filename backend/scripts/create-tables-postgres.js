const { query } = require('../utilities/database');

const createTables = async () => {
  try {
    console.log('Creating tables in PostgreSQL...');

    // Department - Drop and recreate
    await query(`DROP TABLE IF EXISTS Department CASCADE`);
    await query(`
      CREATE TABLE Department (
        dept_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        dept_name VARCHAR(100) NOT NULL,
        doctor_id INTEGER REFERENCES "User"(user_id) ON DELETE SET NULL,
        total_hours_required INTEGER
      )
    `);
    console.log('✅ Created Department table');

    // Academic_Level_Fees - Drop and recreate
    await query(`DROP TABLE IF EXISTS Academic_Level_Fees CASCADE`);
    await query(`
      CREATE TABLE Academic_Level_Fees (
        academic_level INTEGER NOT NULL,
        semester VARCHAR(20) NOT NULL,
        total_fees DECIMAL(10,2) NOT NULL,
        max_hours INTEGER,
        min_hours INTEGER,
        hour_price DECIMAL(10,2) NOT NULL,
        PRIMARY KEY (academic_level, semester)
      )
    `);
    console.log('✅ Created Academic_Level_Fees table');

    // Courses - Drop and recreate
    await query(`DROP TABLE IF EXISTS Courses CASCADE`);
    await query(`
      CREATE TABLE Courses (
        course_code VARCHAR(20) PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        credit_hours INTEGER NOT NULL
      )
    `);
    console.log('✅ Created Courses table');

    // User - Drop and recreate
    await query(`DROP TABLE IF EXISTS "User" CASCADE`);
    await query(`
      CREATE TABLE "User" (
        user_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        password VARCHAR(255) NOT NULL,
        f_name VARCHAR(50) NOT NULL,
        l_name VARCHAR(50) NOT NULL,
        email VARCHAR(100) UNIQUE NOT NULL,
        account_status TEXT CHECK(account_status IN ('pending', 'approved', 'rejected', 'suspended')) DEFAULT 'pending' NOT NULL,
        role TEXT CHECK(role IN ('Student', 'Doctor', 'Admin')) NOT NULL,
        document VARCHAR(255),
        image_url VARCHAR(255),
        is_email_verified BOOLEAN DEFAULT FALSE,
        email_verification_token TEXT,
        email_verification_expires TIMESTAMP,
        password_reset_token TEXT,
        password_reset_expires TIMESTAMP
      )
    `);
    console.log('✅ Created User table');

    // Student - Drop and recreate
    await query(`DROP TABLE IF EXISTS Student CASCADE`);
    await query(`
      CREATE TABLE Student (
        user_id INTEGER PRIMARY KEY REFERENCES "User"(user_id) ON DELETE CASCADE,
        academic_level INTEGER,
        semester VARCHAR(20),
        payment_status TEXT CHECK(payment_status IN ('Paid', 'Unpaid', 'Partial')) DEFAULT 'Unpaid',
        paid_amount DECIMAL(10,2) DEFAULT 0.00,
        nfc_tag_id VARCHAR(50) UNIQUE,
        ssn VARCHAR(20) UNIQUE,
        dept_id INTEGER REFERENCES Department(dept_id) ON DELETE SET NULL,
        total_hours INTEGER DEFAULT 0,
        total_gpa DECIMAL(4,2) DEFAULT 0.00,
        FOREIGN KEY (academic_level, semester) REFERENCES Academic_Level_Fees(academic_level, semester) ON DELETE SET NULL
      )
    `);
    console.log('✅ Created Student table');

    // Doctor - Drop and recreate
    await query(`DROP TABLE IF EXISTS Doctor CASCADE`);
    await query(`
      CREATE TABLE Doctor (
        user_id INTEGER PRIMARY KEY REFERENCES "User"(user_id) ON DELETE CASCADE,
        dept_id INTEGER REFERENCES Department(dept_id) ON DELETE SET NULL,
        specialization VARCHAR(255),
        permission VARCHAR(50)
      )
    `);
    console.log('✅ Created Doctor table');

    // Admin - Drop and recreate
    await query(`DROP TABLE IF EXISTS Admin CASCADE`);
    await query(`
      CREATE TABLE Admin (
        user_id INTEGER PRIMARY KEY REFERENCES "User"(user_id) ON DELETE CASCADE,
        permissions_level INTEGER
      )
    `);
    console.log('✅ Created Admin table');

    // Room - Drop and recreate
    await query(`DROP TABLE IF EXISTS Room CASCADE`);
    await query(`
      CREATE TABLE Room (
        room_id VARCHAR(50) PRIMARY KEY,
        room_name VARCHAR(100) NOT NULL,
        capacity INTEGER NOT NULL,
        type VARCHAR(50) NOT NULL,
        location VARCHAR(100)
      )
    `);
    console.log('✅ Created Room table');

    // Class - Drop and recreate
    await query(`DROP TABLE IF EXISTS Enrollment CASCADE`);
    await query(`DROP TABLE IF EXISTS Lecture CASCADE`);
    await query(`DROP TABLE IF EXISTS Material CASCADE`);
    await query(`DROP TABLE IF EXISTS Class CASCADE`);
    await query(`
      CREATE TABLE Class (
        class_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        course_code VARCHAR(20) REFERENCES Courses(course_code) ON DELETE CASCADE,
        doctor_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        semester VARCHAR(20) NOT NULL,
        level INTEGER NOT NULL,
        capacity INTEGER
      )
    `);
    console.log('✅ Created Class table');

    // Lecture - Drop and recreate
    await query(`DROP TABLE IF EXISTS Lecture CASCADE`);
    await query(`
      CREATE TABLE Lecture (
        lec_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        room_id VARCHAR(50),
        date DATE NOT NULL,
        day VARCHAR(20),
        time TIME NOT NULL,
        start_time TIMESTAMP,
        end_time TIMESTAMP,
        type VARCHAR(50) NOT NULL,
        status TEXT DEFAULT 'open',
        topic VARCHAR(255),
        title VARCHAR(255),
        meeting_link VARCHAR(255),
        attendance_code VARCHAR(50)
      )
    `);
    console.log('✅ Created Lecture table');

    // Material
    await query(`
      CREATE TABLE Material (
        material_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        lec_id INTEGER REFERENCES Lecture(lec_id) ON DELETE CASCADE,
        name VARCHAR(255) NOT NULL,
        type VARCHAR(50) NOT NULL,
        file_path VARCHAR(255),
        upload_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        url VARCHAR(255),
        document VARCHAR(255),
        summarize TEXT,
        uploaded_at TIMESTAMP
      )
    `);
    console.log('✅ Created Material table');

    // Enrollment
    await query(`
      CREATE TABLE Enrollment (
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        PRIMARY KEY (class_id, user_id)
      )
    `);
    console.log('✅ Created Enrollment table');

    // Grades - Drop and recreate
    await query(`DROP TABLE IF EXISTS Grades CASCADE`);
    await query(`
      CREATE TABLE Grades (
        grade_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        generate_at TIMESTAMP,
        attendance INTEGER,
        practical INTEGER,
        project INTEGER,
        midterm INTEGER,
        final INTEGER,
        gpa DECIMAL(5,2),
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        doctor_id INTEGER REFERENCES "User"(user_id) ON DELETE SET NULL,
        max_attendance INTEGER,
        max_practical INTEGER,
        max_midterm INTEGER,
        max_final INTEGER,
        max_project INTEGER
      )
    `);
    console.log('✅ Created Grades table');

    // Attendance - Drop and recreate
    await query(`DROP TABLE IF EXISTS Attendance CASCADE`);
    await query(`
      CREATE TABLE Attendance (
        attendance_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        lec_id INTEGER REFERENCES Lecture(lec_id) ON DELETE CASCADE,
        time TIMESTAMP,
        early_check INTEGER DEFAULT 0,
        late_check INTEGER DEFAULT 0,
        method VARCHAR(50),
        room_id VARCHAR(50)
      )
    `);
    console.log('✅ Created Attendance table');

    // Questions - Drop and recreate
    await query(`DROP TABLE IF EXISTS Answers CASCADE`);
    await query(`DROP TABLE IF EXISTS Questions CASCADE`);
    await query(`
      CREATE TABLE Questions (
        questions_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        text TEXT NOT NULL,
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        doctor_id INTEGER REFERENCES "User"(user_id) ON DELETE SET NULL,
        time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);
    console.log('✅ Created Questions table');

    // Answers
    await query(`
      CREATE TABLE Answers (
        answer_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        question_id INTEGER REFERENCES Questions(questions_id) ON DELETE CASCADE,
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        content TEXT NOT NULL,
        time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);
    console.log('✅ Created Answers table');

    // Notification - Drop and recreate with correct schema
    await query(`DROP TABLE IF EXISTS User_Notification CASCADE`);
    await query(`DROP TABLE IF EXISTS Class_Notification CASCADE`);
    await query(`DROP TABLE IF EXISTS Notification CASCADE`);
    
    await query(`
      CREATE TABLE Notification (
        notification_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        type VARCHAR(50) NOT NULL,
        title VARCHAR(255) NOT NULL,
        message TEXT NOT NULL,
        reference_id INTEGER,
        answer_id INTEGER,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
      )
    `);
    console.log('✅ Created Notification table');

    // User_Notification
    await query(`
      CREATE TABLE User_Notification (
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        notification_id INTEGER REFERENCES Notification(notification_id) ON DELETE CASCADE,
        is_read BOOLEAN DEFAULT FALSE,
        PRIMARY KEY (user_id, notification_id)
      )
    `);
    console.log('✅ Created User_Notification table');

    // Class_Notification
    await query(`
      CREATE TABLE Class_Notification (
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        notification_id INTEGER REFERENCES Notification(notification_id) ON DELETE CASCADE,
        PRIMARY KEY (class_id, notification_id)
      )
    `);
    console.log('✅ Created Class_Notification table');

    // Prerequisite
    await query(`DROP TABLE IF EXISTS Prerequisite CASCADE`);
    await query(`
      CREATE TABLE Prerequisite (
        course_code VARCHAR(20) REFERENCES Courses(course_code) ON DELETE CASCADE,
        prerequisite_code VARCHAR(20) REFERENCES Courses(course_code) ON DELETE CASCADE,
        PRIMARY KEY (course_code, prerequisite_code)
      )
    `);
    console.log('✅ Created Prerequisite table');

    // StudyOutput
    await query(`DROP TABLE IF EXISTS StudyOutput CASCADE`);
    await query(`
      CREATE TABLE StudyOutput (
        output_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        class_id INTEGER REFERENCES Class(class_id) ON DELETE CASCADE,
        material_id INTEGER REFERENCES Material(material_id) ON DELETE CASCADE,
        user_id INTEGER REFERENCES "User"(user_id) ON DELETE CASCADE,
        tool_type VARCHAR(50) NOT NULL,
        options_key VARCHAR(255),
        options_json JSONB,
        content_json JSONB,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(class_id, material_id, user_id, tool_type, options_key)
      )
    `);
    console.log('✅ Created StudyOutput table');

    console.log('\n✅ All tables created successfully!');
    process.exit(0);
  } catch (err) {
    console.error('Error creating tables:', err);
    process.exit(1);
  }
};

createTables();
